SPECIAL = {'space': ' ', 'dot': chr(7), 'left': chr(17), 'right': chr(16), 'up': chr(30), 'down': chr(31),
           'theta': chr(1), 'arrow': chr(26), 'ellipsis': chr(8), 'dpad': chr(9),
           'sup2': chr(18), 'supminus': chr(19), 'sup1': chr(20), 'times': chr(21), 'divide': chr(22)}


def parse(src, rows):
    glyphs, lines, i = {}, src.strip('\n').split('\n'), 0
    while i < len(lines):
        name = lines[i]
        block = lines[i + 1:i + 1 + rows]
        assert len(block) == rows and all(len(r) == len(block[0]) for r in block), name
        glyphs[SPECIAL.get(name, name)] = block
        i += 1 + rows
    return glyphs


def embolden(rows):
    out = []
    for r in rows:
        bits = [c == '#' for c in r] + [False]
        out.append(''.join('#' if b or (i and bits[i - 1]) else '.' for i, b in enumerate(bits)))
    return out


def tables(glyphs, rows):
    widths, data = [0] * 128, []
    for code in range(128):
        g = glyphs.get(chr(code))
        if not g:
            continue
        widths[code] = len(g[0])
        bits = ''.join(r.replace('#', '1').replace('.', '0') for r in g)
        bits += '0' * (-len(bits) % 8)
        data += [int(bits[i:i + 8], 2) for i in range(0, len(bits), 8)]
    return widths, data


def c_array(name, values, per_line=16):
    lines = ['const uint8_t %s[%d] = {' % (name, len(values))]
    for i in range(0, len(values), per_line):
        lines.append('\t' + ', '.join('0x%02X' % v for v in values[i:i + per_line]) + ',')
    lines.append('};')
    return '\n'.join(lines)


